// Regenerates src/data/preflopVsRandom.json with EXACT equities vs a random hand, from the exact preflop table:
// each class = average over its combos of the average over all 1,225 non-conflicting opponent combos.
// Run: npx tsx scripts/gen-vs-random-exact.ts
import { writeFileSync } from 'node:fs';
import data from '../src/data/preflopTable.json';
import { loadTable, preflopEquity } from '../src/engine/preflopTable';
import { ALL_CLASSES, classCombos, expandRange, parseRange } from '../src/engine/range';

const table = loadTable(data as { k: number[]; v: number[] });
const all = expandRange(parseRange('random')).map((c) => c.cards);
const out: Record<string, number> = {};
for (const cls of ALL_CLASSES) {
  let s = 0;
  let n = 0;
  for (const [a, b] of classCombos(cls)) {
    let t = 0;
    let m = 0;
    for (const [c, d] of all) {
      if (c === a || c === b || d === a || d === b) continue;
      t += preflopEquity(table, a, b, c, d);
      m++;
    }
    s += t / m;
    n++;
  }
  out[cls] = Math.round((s / n) * 1e6) / 1e6;
}
const ranking = Object.entries(out)
  .sort((x, y) => y[1] - x[1] || x[0].localeCompare(y[0]))
  .map(([c]) => c);
writeFileSync(
  new URL('../src/data/preflopVsRandom.json', import.meta.url),
  JSON.stringify({ method: 'Exact: each hand class vs one uniformly random opponent hand (blockers respected), averaged over every combo pair using the exact preflop table (all 1,712,304 boards per matchup); generated by scripts/gen-vs-random-exact.ts', exact: true, equity: out, ranking }, null, 1),
);
console.log('AA', out.AA, 'KK', out.KK, '72o', out['72o'], '32o', out['32o']);
