// Generates src/data/preflopVsRandom.json: each of the 169 classes' all-in equity vs one random hand.
// Monte Carlo, 1,000,000 trials per class with a fixed seed (95% CI ≈ ±0.1%). Run: npm run gen:vsrandom
import { writeFileSync } from 'node:fs';
import { ALL_CLASSES, classCombos, parseRange } from '../src/engine/range';
import { equityVsRange } from '../src/engine/equity';

const random = parseRange('random');
const out: Record<string, number> = {};
let i = 0;
for (const cls of ALL_CLASSES) {
  const hero = classCombos(cls)[0];
  const r = equityVsRange(hero, random, [], { mode: 'mc', iterations: 1_000_000, seed: 1000 + i++ });
  out[cls] = Math.round(r.equity * 100000) / 100000;
  process.stdout.write(`${cls} ${(r.equity * 100).toFixed(2)}\n`);
}
const ranked = Object.entries(out).sort((a, b) => b[1] - a[1]).map(([c]) => c);
writeFileSync(
  new URL('../src/data/preflopVsRandom.json', import.meta.url),
  JSON.stringify({ method: 'Monte Carlo, 1,000,000 trials per hand class vs a uniformly random hand (blockers respected), fixed seeds; generated by scripts/gen-vs-random.ts', equity: out, ranking: ranked }, null, 1),
);
